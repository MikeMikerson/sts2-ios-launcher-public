"""Workaround 9: the C source of the Mono library's P/Invoke override table.

The .NET native libraries (libSystem.Native and friends) are linked statically into the library and their symbols are
not exported. AOT code calls them directly (DirectPInvokes), but when the interpreter calls a P/Invoke itself, for
example after tiering up and inlining Stopwatch.GetTimestamp into game code, Mono looks the library up at runtime,
finds nothing and throws DllNotFoundException. This table maps each (library, entry point) the managed assemblies
declare to its address, and installs it with mono_loader_install_pinvoke_override when the library loads.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

# This repository's own native libraries, linked in the same way (tools/build_texture_encoder.py).
OWN_LIBRARY_PREFIX = "libsts2_"
LOOKUP = """static int
sts2_pinvoke_cmp (const char *lib, const char *entry, const struct sts2_pinvoke *p)
{
\tint c = strcmp (lib, p->lib);
\treturn c ? c : strcmp (entry, p->entry);
}

static void *
sts2_pinvoke_override (const char *lib, const char *entry)
{
\tsize_t lo = 0, hi = sizeof (sts2_pinvokes) / sizeof (sts2_pinvokes [0]);
\tif (!lib || !entry)
\t\treturn NULL;
\twhile (lo < hi) {
\t\tsize_t mid = (lo + hi) / 2;
\t\tint c = sts2_pinvoke_cmp (lib, entry, &sts2_pinvokes [mid]);
\t\tif (c == 0)
\t\t\treturn sts2_pinvokes [mid].addr;
\t\tif (c < 0)
\t\t\thi = mid;
\t\telse
\t\t\tlo = mid + 1;
\t}
\treturn NULL;
}

extern void mono_loader_install_pinvoke_override (void *(*override_fn) (const char *, const char *));

__attribute__((constructor)) static void
sts2_install_pinvoke_override (void)
{
\tmono_loader_install_pinvoke_override (sts2_pinvoke_override);
}
"""


def archive_symbols(archives: list[Path]) -> tuple[set[str], set[str]]:
    """Return the .NET native library names among the linked archives, and the symbols they define."""
    libraries, defined = set(), set()
    for path in archives:
        if path.name.startswith(("libSystem.", OWN_LIBRARY_PREFIX)):
            libraries.add(path.name[:-2])
        if path.name.startswith(("libSystem.", "libbrotli", OWN_LIBRARY_PREFIX)):  # Brotli is declared under libSystem.IO.Compression.Native
            output = subprocess.run(["nm", "-g", "-U", "-j", str(path)], capture_output=True, text=True, check=True).stdout
            defined |= {symbol[1:] for symbol in output.split() if symbol.startswith("_")}
    return libraries, defined


def table_entries(declared: list[str], libraries: set[str], defined: set[str]) -> list[tuple[str, str]]:
    """Choose the declared "<library>\\t<entry point>" lines the linked archives can answer."""
    entries = []
    for line in declared:
        library, entry = line.split("\t")
        if library in libraries and entry in defined:
            entries.append((library, entry))
    return sorted(entries)  # the lookup is a binary search, in strcmp order


def render(entries: list[tuple[str, str]]) -> str:
    parts = ["// Generated by tools/mono/pinvoke_table.py.\n#include <stddef.h>\n#include <string.h>\n\n"]
    parts += [f"extern void {symbol} (void);\n" for symbol in sorted({entry for _, entry in entries})]
    parts.append("\nstruct sts2_pinvoke { const char *lib, *entry; void *addr; };\n\n")
    parts.append("static const struct sts2_pinvoke sts2_pinvokes[] = {\n")
    parts += [f'\t{{ "{library}", "{entry}", (void *){entry} }},\n' for library, entry in entries]
    parts.append("};\n\n")
    parts.append(LOOKUP)
    return "".join(parts)
